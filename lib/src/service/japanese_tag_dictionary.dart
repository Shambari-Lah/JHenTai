  /// Translate English tag into Japanese.
  /// Sourced strictly from English (key) without using Chinese.
  static String? translate(String namespace, String key) {
    final cleanNs = namespace.toLowerCase().trim();
    final cleanKey = key.toLowerCase().trim();

    // 1. Check category (rows)
    if (cleanNs == 'rows') {
      if (categoryMap.containsKey(cleanKey)) {
        return categoryMap[cleanKey];
      }
    }

    // 2. Exact match with namespace
    final nsKey = '$cleanNs:$cleanKey';
    if (tagMap.containsKey(nsKey)) {
      return tagMap[nsKey];
    }

    // 3. Exact match with key across any namespace
    if (tagMap.containsKey(cleanKey)) {
      return tagMap[cleanKey];
    }

    // 4. Try matching without underscores
    final spaceKey = cleanKey.replaceAll('_', ' ');
    final spaceNsKey = '$cleanNs:$spaceKey';
    if (tagMap.containsKey(spaceNsKey)) {
      return tagMap[spaceNsKey];
    }
    if (tagMap.containsKey(spaceKey)) {
      return tagMap[spaceKey];
    }

    // 5. Intelligent Compound rule matching for multi-word tags
    final words = spaceKey.split(' ');
    if (words.length >= 2) {
      final firstWord = words.first;
      final restWords = words.sublist(1).join(' ');
      final lastWord = words.last;
      final beforeWords = words.sublist(0, words.length - 1).join(' ');

      // Prefix match: e.g. "sole female", "dark skin"
      if (prefixMap.containsKey(firstWord)) {
        final restJa = translate(cleanNs, restWords);
        if (restJa != null) {
          return '${prefixMap[firstWord]}$restJa';
        }
      }

      // Suffix match: e.g. "... uniform", "... swimsuit"
      if (suffixMap.containsKey(lastWord)) {
        final beforeJa = translate(cleanNs, beforeWords);
        if (beforeJa != null) {
          return '$beforeJa${suffixMap[lastWord]}';
        }
      }
    }

    return null;
  }

  /// Search dictionary for query (supports searching by Japanese or English)
  static List<({String namespace, String key, String japanese})> search(String query) {
    final cleanQuery = query.toLowerCase().trim();
    if (cleanQuery.isEmpty) {
      return [];
    }

    final List<({String namespace, String key, String japanese})> results = [];
    tagMap.forEach((nsKey, ja) {
      if (ja.contains(cleanQuery) || nsKey.contains(cleanQuery)) {
        final colonIdx = nsKey.indexOf(':');
        final ns = colonIdx != -1 ? nsKey.substring(0, colonIdx) : 'other';
        final k = colonIdx != -1 ? nsKey.substring(colonIdx + 1) : nsKey;
        results.add((namespace: ns, key: k, japanese: ja));
      }
    });
    return results;
  }
